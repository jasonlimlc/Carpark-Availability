/**
 * Calculates distance between two coordinates in kilometers using Haversine formula
 */
export function calculateDistanceKm(
  lat1: number,
  lon1: number,
  lat2: number,
  lon2: number
): number {
  const R = 6371; // Earth radius in km
  const dLat = deg2rad(lat2 - lat1);
  const dLon = deg2rad(lon2 - lon1);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(deg2rad(lat1)) *
      Math.cos(deg2rad(lat2)) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Number((R * c).toFixed(2));
}

function deg2rad(deg: number): number {
  return deg * (Math.PI / 180);
}

/**
 * Format distance nicely (e.g., "350 m" or "2.4 km")
 */
export function formatDistance(distanceKm?: number): string {
  if (distanceKm === undefined) return '--';
  if (distanceKm < 1) {
    return `${Math.round(distanceKm * 1000)} m`;
  }
  return `${distanceKm.toFixed(1)} km`;
}

/**
 * Status color and label based on available lots
 */
export function getLotAvailabilityStatus(available: number, total: number) {
  const ratio = total > 0 ? available / total : 0;
  if (available === 0) {
    return {
      label: 'Full',
      color: 'text-rose-400',
      bgColor: 'bg-rose-500/10',
      borderColor: 'border-rose-500/30',
      indicatorColor: 'bg-rose-500',
      badgeBg: 'bg-rose-950/80',
    };
  }
  if (available < 15 || ratio < 0.1) {
    return {
      label: 'Crowded',
      color: 'text-amber-400',
      bgColor: 'bg-amber-500/10',
      borderColor: 'border-amber-500/30',
      indicatorColor: 'bg-amber-500',
      badgeBg: 'bg-amber-950/80',
    };
  }
  if (available < 50 || ratio < 0.25) {
    return {
      label: 'Moderate',
      color: 'text-yellow-400',
      bgColor: 'bg-yellow-500/10',
      borderColor: 'border-yellow-500/30',
      indicatorColor: 'bg-yellow-500',
      badgeBg: 'bg-yellow-950/80',
    };
  }
  return {
    label: 'Available',
    color: 'text-emerald-400',
    bgColor: 'bg-emerald-500/10',
    borderColor: 'border-emerald-500/30',
    indicatorColor: 'bg-emerald-500',
    badgeBg: 'bg-emerald-950/80',
  };
}
